// msdbProcs are the sp_ and sysmail_ procedures msdb ships, lower-cased:
// SELECT LOWER(name) FROM msdb.sys.procedures WHERE is_ms_shipped = 1 AND
// (name LIKE 'sp[_]%' OR name LIKE 'sysmail[_]%'), run on SQL Server 17.0.1155
// (2026-11-17; 13's set is a subset). None shares a name with a resource-database
// procedure. Each is admin however it is qualified (execTarget): after USE msdb,
// which is read, an unqualified sp_send_dbmail is msdb's own, and the
// classifier runs without a connection, so it cannot know the database. The
// Agent reads on readMsdbProcs keep their own rule.
var msdbProcs = func() map[string]bool {
	m := map[string]bool{}
	for _, name := range strings.Fields(msdbProcNames) {
		m[name] = true
	}
	return m
}()

